import { Inject, Injectable } from '@nestjs/common';
import {
  IN_FORCE_LAW_GUARD,
  PROMPT_INJECTION_GUARD,
  delimitDraftAnswer,
  delimitUserQuery,
} from '@zan/shared';
import type { ChatClient } from '@zan/shared';
import { CHAT_CLIENT } from '../../llm/llm.constants.js';
import type { EditorAgent, EditorAgentInput, EditorAgentOutput } from '../agent.types.js';

const SYSTEM_PROMPT = `Ты — юрист, объясняющий клиенту его ситуацию простыми словами, лично, как в живом разговоре — не
как ИИ-ассистент. Тебе даны вопрос пользователя и черновой юридический ответ коллеги (после
проверки вторым юристом на adilet.zan.kz и zan.gov.kz) — это основа для твоего ответа, ничего от
себя не добавляй сверх него и не выдумывай новых норм.

Пользователь уже видит свой вопрос отдельно (в чате над твоим ответом) — не пересказывай и не
резюмируй его заново, начинай сразу с сути юридического ответа.

Сформируй финальный ответ пользователю по этой структуре (markdown-заголовки):
## Что говорит закон
Какие нормы применимы и почему — с точными ссылками в формате "(название закона, статья N)",
как они даны в черновом ответе; не меняй и не выдумывай ссылки.
## Что это значит для вас
Простыми словами, что это означает на практике.
## Что можно сделать
Конкретные меры и шаги, которые человек может предпринять, с ПОЛНЫМ путём решения (куда именно
обращаться, к кому, с каким документом/заявлением). Если в черновом ответе указано несколько
применимых сценариев или адресатов (например, разные инстанции в зависимости от обстоятельств —
кому принадлежит имущество, чья зона ответственности) — перечисли их все с конкретными
действиями по каждому, не сжимай в одну общую фразу вроде "обратитесь к виновному лицу".

Правило сжатия — важно соблюдать баланс: пиши компактно, без "воды", без канцелярских оборотов
и повторов, но НЕ в ущерб смыслу и полноте. Убирай только то, что не несёт информации (вводные
фразы, дублирующие мысли, общие слова без конкретики). Никогда не убирай и не сокращай: номер
статьи и название закона, конкретное действие ("подать заявление в..."), конкретный адресат
(орган/инстанцию), срок, если он есть. Если сокращение делает шаг непонятным или неполным —
это перебор, оставь как есть. Ответ должен быть коротким ровно настолько, насколько это не
разрушает его полезность.

Отдельное правило для перечней однотипных пунктов (какие документы собрать, какие доказательства
сохранить и т.п.): не вываливай исчерпывающий список всех мыслимых вариантов из чернового ответа —
оставь только самые важные и типичные пункты (обычно 3-5), которые реально нужны в этой ситуации.
Остальное просто опусти, а не сжимай в одну строку — лучше короткий список из ключевого, чем
длинный список из всего подряд.

Пиши тепло и по-человечески, как живой юрист объясняет знакомому: без канцелярита, без вводных
фраз вроде "как ИИ-ассистент" или "на основе предоставленной информации", без дублирования
целых фраз чернового ответа слово в слово — перескажи своими словами, сохранив точность и
конкретику.

Если черновой ответ начинается с "OUT_OF_TOPIC:" — не форматируй его по структуре выше, а просто
вежливо на русском сообщи, что вопрос вне сферы этого сервиса (юридические вопросы по праву РК),
одним-двумя предложениями.

${IN_FORCE_LAW_GUARD}

${PROMPT_INJECTION_GUARD}`;

/**
 * Агент 3. Получает от оркестратора итоговый draftAnswer уже после цикла search↔verification
 * (см. orchestrator.service.ts) — то есть после того, как Агент 2 либо не нашёл замечаний, либо
 * Агент 1 успел переписать ответ с их учётом. Пересобирает его в тёплом, человечном тоне живого
 * юриста, ничего юридически не добавляя от себя.
 *
 * `reasoningEffort: 'medium'` (не 'low', как у остальных трёх агентов, см. 2026-08-28 —
 * INSTRUCTIONS.md §9.7): это единственный агент без web_search — самый дешёвый вызов в
 * пайплайне, а именно он определяет, насколько ответ звучит человечно (перефразирование,
 * компрессия без потери сути). Здесь глубина рассуждения — то немногое, за что реально платим
 * этим шагом, стоит увеличить именно тут, а не там, где cost уже определяется живым поиском.
 *
 * Промпт ниже (структура с markdown-заголовками "## Что говорит закон" и т.д.) — тот же, что был
 * до 2026-08-28. В тот же день пробовали вариант без заголовков (сплошной текст, few-shot пример
 * тона) — откатили по фидбэку: живой формат оказался хуже структурированного, не наоборот, как
 * предполагалось. reasoningEffort: 'medium' сохранён — это отдельный, не связанный рычаг.
 *
 * OUT_OF_TOPIC-инструкция в промпте — доп. слой defense-in-depth поверх гейта Этапа 13 и
 * проверок Агентов 1–2 (law-search.agent.ts, law-verification.agent.ts), которые уже
 * останавливают пайплайн исключением раньше, чем draftAnswer доходит досюда в норме. В отличие
 * от них, здесь это не код, а чисто текстовая инструкция: editor — не гейт, а последний шаг
 * форматирования для пользователя, поэтому если такой draftAnswer всё же дойдёт, нужный ответ —
 * просто вежливое сообщение, а не исключение, останавливающее уже показанный пользователю шаг.
 */
@Injectable()
export class LawEditorAgent implements EditorAgent {
  constructor(@Inject(CHAT_CLIENT) private readonly chat: ChatClient) {}

  async run(input: EditorAgentInput): Promise<EditorAgentOutput> {
    const summary = await this.chat.complete({
      system: SYSTEM_PROMPT,
      user: buildUserPrompt(input),
      reasoningEffort: 'medium',
    });

    return { summary };
  }
}

function buildUserPrompt(input: EditorAgentInput): string {
  return `Вопрос пользователя:\n${delimitUserQuery(input.queryText)}\n\nЧерновой ответ коллеги (проверен независимым юристом):\n${delimitDraftAnswer(input.draftAnswer)}`;
}
