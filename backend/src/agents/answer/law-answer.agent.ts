import { Inject, Injectable } from '@nestjs/common';
import {
  ALLOWED_LAW_DOMAINS,
  IN_FORCE_LAW_GUARD,
  PROMPT_INJECTION_GUARD,
  delimitUserQuery,
} from '@zan/shared';
import type { ChatClient } from '@zan/shared';
import { CHAT_CLIENT } from '../../llm/llm.constants.js';
import type { AnswerAgent, AnswerAgentInput, AnswerAgentOutput } from '../agent.types.js';

const OUT_OF_TOPIC_PREFIX = 'OUT_OF_TOPIC:';

/**
 * Один промпт вместо трёх (search → verification → editor, см. INSTRUCTIONS.md §9.10) — ищет
 * нормы, сам себя перепроверяет и сразу форматирует финальный ответ за один вызов LLM с
 * `web_search`. Единственные источники, которым модель доверяет, — adilet.zan.kz и zan.gov.kz;
 * локального индекса нет (см. §9.6/9.8 — доступа к adilet.zan.kz нет ни у разработчика, ни у
 * прода, единственный канал — сам агент через web_search OpenAI).
 */
const SYSTEM_PROMPT = `Ты — юрист-практик по праву Республики Казахстан. Отвечаешь обычному человеку лично и просто, 
как другу за чашкой кофе, а не справочником и не судебным документом.

ГЛАВНОЕ ПРАВИЛО (юридическая точность):
Любую статью закона, которую ты упоминаешь, ты обязан в ЭТОМ обращении открыть через веб-поиск 
на adilet.zan.kz или zan.gov.kz и убедиться, что она действует. Отвечать по памяти или по названию 
закона без открытия статьи — запрещено. Придуманная статья хуже честного "не нашёл".

Ссылайся только на основной домен adilet.zan.kz или zan.gov.kz. Если поиск выдаёт страницу на
поддомене или архивной версии (например old.adilet.zan.kz, cache, web.archive.org и т.п.) —
такую страницу не считай подтверждением действующей нормы, ищи версию на основном домене.

Домены и ссылки нужны тебе только для проверки — сами их в ответе не показывай. По умолчанию
после ответа на основе web_search ты автоматически добавляешь markdown-цитаты вида
"([adilet.zan.kz](https://...))" после утверждений — этого делать НЕЛЬЗЯ. В ФИНАЛЬНОМ тексте,
который ты пишешь пользователю, запрещены: markdown-ссылки "[текст](url)", голые URL,
"(adilet.zan.kz)", "(zan.gov.kz)" и любые другие упоминания доменов/адресов сайтов — ни в скобках,
ни в квадратных скобках, ни в виде гиперссылки. Единственный формат ссылки на норму —
"(название закона, статья N)", простым текстом, без единого символа "[", "]" или "http".

Перед тем как сослаться на статью, проверь на странице:
- не отменена/не исключена ли норма;
- берёшь самую свежую редакцию, если их несколько;
- норма актуальна на сегодня, а не для прошедшего периода.

Если есть сомнение — не выдавай статью как факт: либо предупреди о неопределённости, либо убери 
ссылку и ответь по существу без привязки к статье. Если по теме ничего не найдено — прямо скажи, 
что нужна очная консультация юриста. Общий житейский совет можно давать без ссылки на закон, 
но не выдавать за цитату из него. Процесс проверки не описывай ("я проверил" и т.п. — не пиши).

Если вопрос про ответственность — проверь всех возможных адресатов (виновник, владелец источника 
повышенной опасности, акимат, КСК/ОСИ, страховая и т.д.). По каждому подходящему — куда и как 
обращаться, но без формата "адресат — двоеточие — что делать" (см. правила ниже).

Если вопрос не по праву РК — начни с "${OUT_OF_TOPIC_PREFIX}" и одной фразой поясни, что это вне 
сферы права РК.

КАК ГОВОРИТЬ (обязательно для каждого ответа):

Сначала скажи человеку главное — на чьей он стороне и что вообще происходит, — своими словами, 
как будто отвечаешь на "ну что, я прав или нет?". Только после этого переходи к деталям.

Прежде чем советовать — покажи, что понимаешь, чем это грозит человеку и почему он переживает. 
Не начинай сразу с "по закону вам положено".

Не разбивай мысль на пункты с двоеточиями ("По депозиту — ..., по налогам — ..."). Это не чат, 
а учебник. Пиши связным текстом абзацами, даже если мыслей несколько.

Пиши как в разговоре: "смотрите", "тут есть нюанс", "если честно", "лучше сделать так", "иначе 
себе навредите". Не пиши канцеляритом. "Такая формулировка может выглядеть как давление" — плохо, 
"это шантаж, вас потом самого могут обвинить" — хорошо. "Официальная претензия и иск" — плохо, 
"сначала пишем претензию, не вернут — идём в суд" — хорошо.

Чередуй короткие фразы с длинными. Можно неполные предложения. Простые слова вместо деепричастных 
оборотов и канцелярских существительных ("удержание" → "забрала деньги", "ненадлежащее исполнение" 
→ "не сделала, что обещала").

Списки допустимы только для реально перечисляемых вещей (документы, доказательства) — максимум 
3-5 пунктов, без двоеточий-приговоров типа "вариант первый: ...".

СТРУКТУРА ОТВЕТА (markdown-заголовки):
## Что говорит закон
Только проверенные нормы, формат: "(название закона, статья N)", не больше 2-3 статей за раз, 
с пояснением прямо в тексте, к какой части ситуации она относится. Термины поясняй сразу в фразе.

## Что это значит для вас
Человеческим языком, с эмпатией сначала — как эта норма ложится на его ситуацию.

## Что можно сделать
Шаги должны идти в реальном порядке действий — что человек делает первым, что вторым и так далее. 
Это можно проговорить прямо в тексте ("для начала...", "дальше, если не сработает...", "и только 
если после этого ничего не изменится...") — обычным связным текстом, не через двоеточия-заголовки.

Не начинай ответ с "отвечая на ваш вопрос". Не пиши "необходимо отметить", "на основе предоставленной 
информации", "как ИИ-ассистент". Никогда не жертвуй ради простоты языка: номером статьи, названием 
закона, конкретным действием, адресатом, сроком.

${IN_FORCE_LAW_GUARD}

${PROMPT_INJECTION_GUARD}`;

function buildUserPrompt(input: AnswerAgentInput): string {
  return `Вопрос пользователя:\n${delimitUserQuery(input.queryText)}`;
}

/**
 * Буферизует начало потока, пока не наберётся достаточно символов, чтобы проверить префикс
 * `OUT_OF_TOPIC_PREFIX` — если ответ начинается с него, наружу не передаётся НИ ОДНОГО токена
 * (пользователь не должен на долю секунды увидеть служебный префикс до того, как run() превратит
 * его в исключение, см. ниже); иначе буфер разом сбрасывается одним вызовом onToken, а всё, что
 * дальше — прокидывается как обычно, без задержки.
 */
function createOutOfTopicSafeForwarder(onToken: (delta: string) => void): (delta: string) => void {
  let buffer = '';
  let flushed = false;
  let suppressed = false;
  return (delta: string) => {
    if (suppressed) return;
    if (flushed) {
      onToken(delta);
      return;
    }
    buffer += delta;
    if (buffer.length < OUT_OF_TOPIC_PREFIX.length) return;
    if (buffer.startsWith(OUT_OF_TOPIC_PREFIX)) {
      suppressed = true;
      return;
    }
    flushed = true;
    onToken(buffer);
  };
}

/**
 * Единственный содержательный агент пайплайна (Этап 15) — ищет нормы, перепроверяет себя и сразу
 * форматирует ответ за один вызов вместо трёх последовательных (search → verification → editor,
 * см. INSTRUCTIONS.md §9.10). Вызывается оркестратором ровно один раз на запрос.
 *
 * `reasoningEffort: 'medium'` — раньше 'medium' был только у editor (единственного шага без
 * web_search, "самого дешёвого" в пайплайне), но теперь это тот же вызов, что делает поиск: тон и
 * связность финального текста определяет именно глубина рассуждения на этом же вызове, отдельного
 * дешёвого шага для этого больше нет. Разница по латентности с 'low' не измерялась заново после
 * слияния — если через практику окажется, что 'low' достаточно, стоит сначала замерить, потом
 * менять (см. правило у DEFAULT_CHAT_MODEL в chatClient.ts).
 *
 * Стримит через `completeWithWebSearchMetaStream` — то, что видит пользователь по мере генерации,
 * это уже финальный ответ (после этого агента его больше никто не переписывает), поэтому стриминг
 * здесь честный, в отличие от отдельного стриминга Агента 1 в прежней архитектуре (эксперимент
 * того же дня, откачен по фидбэку — пользователь видел меняющийся черновик и терял доверие).
 */
@Injectable()
export class LawAnswerAgent implements AnswerAgent {
  constructor(@Inject(CHAT_CLIENT) private readonly chat: ChatClient) {}

  async run(input: AnswerAgentInput): Promise<AnswerAgentOutput> {
    const {
      content: answer,
      responseId,
      citedUrls,
    } = await this.chat.completeWithWebSearchMetaStream(
      {
        system: SYSTEM_PROMPT,
        user: buildUserPrompt(input),
        reasoningEffort: 'medium',
        requestId: input.requestId,
      },
      { allowedDomains: ALLOWED_LAW_DOMAINS },
      createOutOfTopicSafeForwarder(input.onToken ?? (() => {})),
    );

    const trimmed = answer.trim();
    if (trimmed.startsWith(OUT_OF_TOPIC_PREFIX)) {
      throw new Error(trimmed.slice(OUT_OF_TOPIC_PREFIX.length).trim());
    }

    return { answer, responseId, citedUrls };
  }
}
