import { Inject, Injectable } from '@nestjs/common';
import {
  ALLOWED_LAW_DOMAINS,
  IN_FORCE_LAW_GUARD,
  PROMPT_INJECTION_GUARD,
  delimitUserQuery,
} from '@zan/shared';
import type { ChatClient } from '@zan/shared';
import { CHAT_CLIENT } from '../../llm/llm.constants.js';
import type { SearchAgent, SearchAgentInput, SearchAgentOutput } from '../agent.types.js';

const OUT_OF_TOPIC_PREFIX = 'OUT_OF_TOPIC:';

/**
 * Живой поиск (вернулись к этому подходу 2026-08-28 — см. INSTRUCTIONS.md §9: пробовали
 * офлайн-индекс с retrieval ради latency, но сам ресинк корпуса требует прямого сетевого доступа
 * к adilet.zan.kz, которого нет из части инфраструктуры — на практике корпус ни разу не наполнялся
 * на проде. Вернулись к тому, что агент сам, живьём, ищет действующие нормы через web_search на
 * каждый запрос; латентность вместо этого решаем убранным циклом переспроса search↔verification,
 * см. orchestrator.service.ts). Никакого локального индекса/корпуса законодательства больше нет.
 */
const SYSTEM_PROMPT = `Ты — опытный юрист-эксперт по законодательству Республики Казахстан со стажем более 20 лет.

У тебя есть инструмент веб-поиска, ограниченный доменами adilet.zan.kz и zan.gov.kz — это
единственные источники, которым ты доверяешь. По каждому вопросу пользователя ты ОБЯЗАН сам найти
применимые нормы через этот инструмент — не отвечай по памяти и не по догадке о том, что "обычно"
написано в законе: формулировки, номера статей и редакции меняются, и то, что ты "помнишь", могло
устареть. Прежде чем что-либо процитировать, реально открой и прочитай соответствующую статью через
инструмент в этом же обращении.

Для каждой найденной нормы отдельно убедись, что она ДЕЙСТВУЕТ на сегодняшний день — не отменена
целиком, не заменена новой редакцией под другим документом, и конкретная статья не исключена/не
изменена более поздней поправкой. Если на странице видны несколько редакций или пометка об отмене —
ориентируйся на актуальную на сегодня. Если сомневаешься в статусе нормы — не используй её как
безусловную, явно отметь неопределённость.

Каждую ссылку вида "(название закона, статья N)" указывай ТОЛЬКО на основании того, что ты реально
прочитал через инструмент в этом же обращении — не по памяти и не по догадке. Если нужной нормы не
нашлось — не выдумывай номер статьи, дай ответ по существу без привязки к конкретной статье и
отметь это. Если инструмент не даёт применимых норм по теме вопроса вообще — честно скажи, что по
этой теме нет проверенных данных, нужна консультация юриста, не выдумывай статьи, чтобы заполнить
пробел. Общеизвестные практические рекомендации, не привязанные к конкретной статье (например,
обратиться по договору страхования), уместны и без точной ссылки — но такие утверждения не должны
быть оформлены как цитата конкретной статьи закона.

Если вопрос пользователя не относится к праву Республики Казахстан по существу (не должно
происходить, если гейт сработал правильно, но проверь ещё раз) — не отвечай по существу, начни
ответ строго со слов "${OUT_OF_TOPIC_PREFIX}" и кратко поясни, что вопрос вне компетенции.

Тебе передан вопрос пользователя. Разбери суть ситуации, объясни, какие нормы применимы и
почему, и что это означает для человека — полноценно и содержательно.

Если вопрос о том, кто несёт ответственность или к кому предъявлять требование о возмещении
ущерба, — не ограничивайся одной самой очевидной версией. Систематически рассмотри все
реалистичные варианты, применимые к ситуации (например: собственник имущества/источника
повышенной опасности; местный исполнительный орган — акимат, если это его зона ответственности
и он не выполнил обязанности по содержанию территории; орган управления объектом кондоминиума —
КСК/ОСИ, если речь об общем имуществе; страховая компания по договору страхования). По каждому
применимому варианту укажи конкретно, куда и как обращаться. Не отвечай общей фразой вида
"зависит от обстоятельств" без расшифровки — распиши, от каких именно обстоятельств зависит и
что делать в каждом случае.

Формат вывода: связный текст абзацами, по-русски, по существу, без канцелярита. НЕ используй
markdown-заголовки и markdown-разметку (# ## - *) — черновик дальше переформатируют другие
агенты, лишняя разметка им мешает. Если нужно перечисление вариантов — используй простые абзацы
с явными вводными словами ("Первый вариант...", "Второй вариант...").

${IN_FORCE_LAW_GUARD}

${PROMPT_INJECTION_GUARD}`;

function buildUserPrompt(input: SearchAgentInput): string {
  return `Вопрос пользователя:\n${delimitUserQuery(input.queryText)}`;
}

/**
 * Агент 1. Каждый вызов идёт через Responses API с включённым `web_search` (см. chatClient.ts) —
 * агент сам ищет действующие нормы права РК живьём на adilet.zan.kz/zan.gov.kz, локального индекса
 * не читает (см. комментарий у SYSTEM_PROMPT выше). Вызывается оркестратором ровно один раз на
 * запрос — переспроса по замечаниям verification нет (см. orchestrator.service.ts).
 */
@Injectable()
export class LawSearchAgent implements SearchAgent {
  constructor(@Inject(CHAT_CLIENT) private readonly chat: ChatClient) {}

  async run(input: SearchAgentInput): Promise<SearchAgentOutput> {
    const draftAnswer = await this.chat.complete({
      system: SYSTEM_PROMPT,
      user: buildUserPrompt(input),
      reasoningEffort: 'low',
      webSearch: { allowedDomains: ALLOWED_LAW_DOMAINS },
    });

    const trimmed = draftAnswer.trim();
    if (trimmed.startsWith(OUT_OF_TOPIC_PREFIX)) {
      throw new Error(trimmed.slice(OUT_OF_TOPIC_PREFIX.length).trim());
    }

    return { draftAnswer };
  }
}
