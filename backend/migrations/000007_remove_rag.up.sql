-- Отказ от RAG (instructions.md §2 "Вызов LLM-агента"): Q&A — прямой
-- streaming-вызов OpenAI (промпт из БД + история треда), без поиска
-- источников в helper/. Откатывает то, что Stage 5 (000005_stage5_agent)
-- добавил в core ради RAG. Схема rag/роль zan_rag/расширение vector
-- принадлежат не zan_core — их удаление вне golang-migrate, см.
-- instructions.md §8 "Удаление RAG на существующем томе".
--
-- 1) core.messages.unverified_sources — флаг сверки процитированных LLM
--    источников с выдачей RAG; сверять больше не с чем.
ALTER TABLE core.messages
    DROP COLUMN unverified_sources;

-- 2) Сид-промпт qa (000005) требует ссылаться только на статьи "из раздела
--    источников", которого в промпте больше нет — без правки модель
--    отвечала бы, что источников нет, на любой вопрос. Обновляется только
--    нетронутый сид: текст, уже отредактированный через /admin/prompts, —
--    решение продукта, миграция его не перетирает.
UPDATE core.agent_prompts
SET prompt_text =
        'Ты — юридический ассистент-консультант для пользователей в Казахстане. '
        'Отвечай по существу заданного вопроса понятным, но профессиональным '
        'языком, опираясь на действующее законодательство Республики Казахстан. '
        'Называй конкретные статьи и законы, только если уверен в их '
        'существовании и номере — никогда не придумывай номера статей, названия '
        'законов или их содержание. Если не уверен в точном ответе, честно скажи '
        'об этом, не выдавай предположение за факт. Если вопроса недостаточно, '
        'чтобы дать содержательный ответ, задай один уточняющий вопрос вместо '
        'того, чтобы гадать. Отвечай на том языке (русский или казахский), на '
        'котором задан вопрос.',
    updated_at = now()
WHERE agent_type = 'qa'
  AND prompt_text =
        'Ты — юридический ассистент-консультант для пользователей в Казахстане. '
        'Отвечай по существу заданного вопроса понятным, но профессиональным '
        'языком. Ссылайся только на статьи закона, реально переданные тебе в '
        'разделе источников — никогда не придумывай номера статей, названия '
        'законов или их содержание. Если источников недостаточно для точного '
        'ответа, честно скажи об этом, не выдавай предположение за факт. Если '
        'вопроса недостаточно, чтобы дать содержательный ответ, задай один '
        'уточняющий вопрос вместо того, чтобы гадать. Отвечай на том языке '
        '(русский или казахский), на котором задан вопрос.';
