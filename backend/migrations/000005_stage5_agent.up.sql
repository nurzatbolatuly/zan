-- 1) core.messages.unverified_sources — флаг, вычисляемый
--    internal/agent.verifySources сразу после ответа LLM (сверка sources,
--    которые процитировала модель, со списком, который реально вернул
--    RagService.Search — backend-roadmap.md §1.4/§5.2, "подозрение на
--    галлюцинацию закона"). Отдаётся в ответе API (backend-roadmap.md §6
--    открытый вопрос №11: "бэк-часть реализуется в любом случае") — поэтому
--    персистится, не только логируется, иначе GET /threads/{id} потерял бы
--    значение после первого ответа. DEFAULT false — валиден и для старых
--    сообщений StubAgent (Stage 3), и для сообщений пользователя (только
--    Sender=assistant реально может нести sources).
ALTER TABLE core.messages
    ADD COLUMN unverified_sources boolean NOT NULL DEFAULT false;

