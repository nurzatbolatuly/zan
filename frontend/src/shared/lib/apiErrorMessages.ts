const FALLBACK: Record<Lang, string> = {
  ru: "Не удалось выполнить запрос. Попробуйте ещё раз.",
  kz: "Сұрауды орындау мүмкін болмады. Қайта көріңіз.",
};

/** Единая точка перевода ошибки API в текст для тоста/inline-сообщения. */
export function describeApiError(error: unknown, lang: Lang): string {
  if (error instanceof ApiError) {
    const code = error.body?.code;
    if (code && code in MESSAGES) return MESSAGES[code][lang];
    return error.body?.message || FALLBACK[lang];
  }
  return FALLBACK[lang];
}
