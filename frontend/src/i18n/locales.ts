/**
 * Этап 13 (бэклог) — поддержка нескольких языков интерфейса: русский и казахский. Только
 * статический текст интерфейса (лейблы, заголовки, кнопки) — сам ответ ассистента (текст от
 * LLM, ссылки на статьи закона, содержимое сгенерированных документов) остаётся на русском
 * независимо от выбранного языка: перевод юридического контента — отдельная, гораздо более
 * рискованная задача (легко исказить смысл нормы права), сознательно не в этом объёме
 * (соответствует решению не добавлять агента-переводчика, см. PLAN.md Этап 13).
 */
export const locales = ['ru', 'kk'] as const;
export type Locale = (typeof locales)[number];
export const defaultLocale: Locale = 'ru';

export function isLocale(value: string): value is Locale {
  return (locales as readonly string[]).includes(value);
}
