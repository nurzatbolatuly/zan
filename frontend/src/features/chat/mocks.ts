export interface AssistantReplyContent {
  metaLabel: string;
  paragraphs: string[];
  sources: ChatSource[];
  findings: ChatFinding[];
  document: ChatDocument | null;
}

/** Единственная точка, откуда рендер читает контент мок-ответа — см. комментарий вверху файла. */
export function getAssistantReplyContent(
  kind: AssistantReplyKind,
  lang: Lang,
): AssistantReplyContent {
  switch (kind) {
    case "qa":
      return {
        metaLabel: ASSISTANT_LABEL[lang],
        paragraphs: QA_PARAGRAPHS[lang],
        sources: QA_SOURCES[lang],
        findings: [],
        document: null,
      };
    case "contract-review":
      return {
        metaLabel: ASSISTANT_LABEL[lang],
        paragraphs: CONTRACT_PARAGRAPHS[lang],
        sources: [],
        findings: CONTRACT_FINDINGS[lang],
        document: null,
      };
    case "document":
      return {
        metaLabel: DOCUMENT_READY_LABEL[lang],
        paragraphs: [],
        sources: [],
        findings: [],
        document: DOCUMENT_CONTENT[lang],
      };
  }
}
